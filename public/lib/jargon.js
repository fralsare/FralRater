export function jargonTermRegex(term) {
  return new RegExp('\\b' + term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\b', 'gi');
}

export function findJargon(text) {
  const hits = [];
  for (const entry of JARGON) {
    const re = jargonTermRegex(entry.term);
    let m;
    while ((m = re.exec(text)) !== null) {
      hits.push({ term: entry.term, plain: entry.plain, cat: entry.cat, index: m.index, snippet: m[0] });
      if (entry.term.includes(' ')) break; // multi-word: one hit is enough for scoring
      if (re.lastIndex === m.index) re.lastIndex++;
    }
  }
  return hits;
}

export function replaceJargon(text) {
  let changes = 0;
  for (const entry of JARGON) {
    const re = jargonTermRegex(entry.term);
    const replaced = text.replace(re, (match) => {
      changes++;
      if (match[0] === match[0].toUpperCase() && match.length > 1) {
        return entry.plain[0].toUpperCase() + entry.plain.slice(1);
      }
      return entry.plain;
    });
    text = replaced;
  }
  return { text, changes };
}
